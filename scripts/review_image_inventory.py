"""Prepare private, hash-backed contact sheets without opening images for review."""

import argparse
from collections import Counter
from datetime import datetime, timezone
from hashlib import sha256
from io import BytesIO, StringIO
import csv
import json
import math
import os
from pathlib import Path
import tempfile
import warnings

from PIL import Image, ImageDraw, ImageFont, ImageOps, UnidentifiedImageError

from import_instagram import PHOTO_EXTENSIONS, check_local_path, open_regular
from prepare_prototype_photos import encoded, save_preserving_existing


ROOT = Path(__file__).resolve().parents[1]
STOP_AT_VIEWS = 16
TILE = (400, 350)
THUMB = (368, 250)
CLASSIFICATIONS = {"cake", "other-bake", "process", "non-product", "uncertain"}
SELECTIONS = {"shortlist", "reserve", "exclude", "hold"}
REPORT_MARKER = "<!-- Generated by review_image_inventory.py; edit batch decisions, not this file. -->"


def json_bytes(value):
    return (json.dumps(value, indent=2, ensure_ascii=True) + "\n").encode("utf-8")


def read_json(path):
    return json.loads(path.read_text(encoding="utf-8"))


def write_new(path, value):
    save_preserving_existing(path, json_bytes(value))


def replace_generated(path, payload):
    path.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.NamedTemporaryFile(dir=path.parent, delete=False) as stream:
        temporary = Path(stream.name)
        stream.write(payload)
    try:
        os.replace(temporary, path)
    finally:
        temporary.unlink(missing_ok=True)


def private_output(path):
    check_local_path(path.absolute())
    path = path.resolve()
    if not path.is_relative_to(ROOT / ".local") or path == ROOT / ".local":
        raise ValueError("Review output must be a named directory below this project's .local.")
    return path


def source_files(root):
    check_local_path(root)
    if not root.is_dir():
        raise ValueError(f"Missing source directory: {root}")
    files = []
    for directory, folders, names in os.walk(root, followlinks=False):
        for name in folders + names:
            check_local_path(Path(directory) / name)
        files.extend(Path(directory) / name for name in names)
        if len(files) > 2000:
            raise ValueError("More than 2000 files; use a separately scoped inventory.")
    return sorted(files, key=lambda path: str(path.relative_to(root)).casefold())


def source_data(path):
    with open_regular(path) as stream:
        data = stream.read(64 * 1024 * 1024 + 1)
    if not data or len(data) > 64 * 1024 * 1024:
        raise ValueError(f"Empty source or source larger than 64 MiB: {path}")
    return data


def inspect_file(path, root, number, usage):
    before = path.stat()
    data = source_data(path)
    digest = sha256(data).hexdigest()
    record = {
        "id": f"P{number:03}", "path": str(path), "relative_path": str(path.relative_to(root)),
        "filename": path.name, "extension": path.suffix.lower(),
        "sha256": digest, "bytes": len(data), "mtime_ns": before.st_mtime_ns,
        "width": None, "height": None, "display_width": None, "display_height": None,
        "format": None, "mode": None, "frames": None, "has_exif": None,
        "decode_status": "unsupported-extension", "error": None,
        "duplicate_of": None, "existing_website_cake_ids": usage.get(digest, []),
    }
    if path.suffix.lower() in PHOTO_EXTENSIONS:
        try:
            with warnings.catch_warnings():
                warnings.simplefilter("error", Image.DecompressionBombWarning)
                with Image.open(BytesIO(data)) as image:
                    record.update(width=image.width, height=image.height, format=image.format,
                                  mode=image.mode, frames=getattr(image, "n_frames", 1),
                                  has_exif=bool(image.getexif()))
                    image.load()
                    display = ImageOps.exif_transpose(image)
                    record.update(display_width=display.width, display_height=display.height,
                                  decode_status="ok" if record["frames"] == 1 else "animated")
        except (OSError, ValueError, UnidentifiedImageError,
                Image.DecompressionBombError, Image.DecompressionBombWarning) as error:
            record.update(decode_status="decode-failed", error=str(error))
    after = path.stat()
    if (before.st_size, before.st_mtime_ns) != (after.st_size, after.st_mtime_ns):
        raise ValueError(f"Source changed during inventory: {path}")
    return record


def groups(items):
    if not items:
        return []
    minimum, maximum = math.ceil(len(items) / 20), len(items) // 15
    if minimum > maximum:
        raise ValueError(f"Cannot partition {len(items)} thumbnails into 15-20 per sheet.")
    count = min(maximum, max(minimum, math.ceil(len(items) / 18)))
    width, extra = divmod(len(items), count)
    result, start = [], 0
    for index in range(count):
        stop = start + width + (index < extra)
        result.append(items[start:stop])
        start = stop
    return result


def render_sheet(records, name, output):
    if not 15 <= len(records) <= 20:
        raise ValueError("Each sheet must contain 15-20 distinct thumbnails.")
    if len({record["sha256"] for record in records}) != len(records):
        raise ValueError("Do not repeat byte-identical images on a contact sheet.")
    font = ImageFont.truetype(str(ROOT / "web" / "assets" / "fonts" / "dm-sans-regular.ttf"), 18)
    canvas = Image.new("RGB", (TILE[0] * 4, 94 + TILE[1] * math.ceil(len(records) / 4)), "#f5ebdd")
    draw = ImageDraw.Draw(canvas)
    draw.text((16, 12), f"{name} | {len(records)} originals | THUMBNAIL INSPECTION ONLY",
              font=font, fill="#34483a")
    draw.text((16, 40), "Full framing retained; no crop, upscaling or publication approval.",
              font=font, fill="#34483a")
    tiles = []
    for index, record in enumerate(records):
        data = source_data(Path(record["path"]))
        if sha256(data).hexdigest() != record["sha256"]:
            raise ValueError(f"Source hash changed before thumbnail generation: {record['path']}")
        with Image.open(BytesIO(data)) as original:
            thumb = ImageOps.exif_transpose(original).convert("RGB")
        thumb.thumbnail(THUMB, Image.Resampling.LANCZOS)
        left, top = (index % 4) * TILE[0], 94 + (index // 4) * TILE[1]
        box = (left + 16 + (THUMB[0] - thumb.width) // 2,
               top + (THUMB[1] - thumb.height) // 2)
        canvas.paste(thumb, box)
        labels = [
            f"{record['id']} | {record['filename']}",
            f"{record['display_width']} x {record['display_height']} | SHA {record['sha256'][:10]}",
            str(Path(record["relative_path"]).parent),
        ]
        y = top + THUMB[1] + 8
        for label in labels:
            if draw.textlength(label, font=font) > TILE[0] - 32:
                raise ValueError(f"Label would be clipped; shorten the label layout, not the filename: {label}")
            draw.text((left + 16, y), label, font=font, fill="#34483a")
            y += 25
        tiles.append({"id": record["id"], "thumbnail_size": list(thumb.size), "position": list(box)})
    payload = encoded(canvas, "JPEG", quality=92, subsampling=0)
    path = output / "sheets" / f"{name}.jpg"
    save_preserving_existing(path, payload)
    return {"id": name, "file": str(Path("sheets") / path.name), "sha256": sha256(payload).hexdigest(),
            "width": canvas.width, "height": canvas.height, "ids": [r["id"] for r in records],
            "tiles": tiles, "review_level": "contact-sheet-only"}


def owner_classifications(path, records):
    if not path:
        return {}
    document = read_json(path)
    if document.get("evidence") != "owner-provided-source-classification" or not document.get("recorded_at"):
        raise ValueError("Owner classifications need explicit source evidence and a recorded date.")
    known = {record["id"]: record for record in records}
    result = {}
    for item in document.get("items", []):
        record = known.get(item.get("id"))
        if not record or item["id"] in result or item.get("sha256") != record["sha256"]:
            raise ValueError("Unknown, duplicate or hash-mismatched owner-classified image.")
        if record["decode_status"] != "ok" or item.get("relative_path", record["relative_path"]) != record["relative_path"]:
            raise ValueError("Owner classification must match a decoded source image and its exact path.")
        if (item.get("classification") not in CLASSIFICATIONS - {"uncertain"}
                or not isinstance(item.get("label"), str) or not item["label"].strip()
                or not isinstance(item.get("reason"), str) or not item["reason"].strip()):
            raise ValueError("Owner classifications need a supported class, label and reason.")
        result[item["id"]] = item
    return result


def prepare(source, output, usage_manifest, owner_path=None):
    source = Path(os.path.abspath(source))
    output = private_output(output)
    if source == output or source.is_relative_to(output) or output.is_relative_to(source):
        raise ValueError("Source and output must not overlap.")
    if output.exists():
        raise ValueError(f"Output already exists; resume it instead of overwriting: {output}")
    usage = {}
    for photo in read_json(usage_manifest)["photos"]:
        usage.setdefault(photo["source_sha256"], []).append(photo["id"])
    files = source_files(source)
    if not files:
        raise ValueError("No source files found.")
    records, seen = [], {}
    for number, path in enumerate(files, 1):
        record = inspect_file(path, source, number, usage)
        record["duplicate_of"] = seen.get(record["sha256"])
        seen.setdefault(record["sha256"], record["id"])
        records.append(record)
    owners = owner_classifications(owner_path, records)
    pending = [r for r in records if r["decode_status"] == "ok" and r["id"] not in owners
               and not r["duplicate_of"] and not r["existing_website_cake_ids"]]
    inventory = {
        "schema_version": 1, "source_root": str(source),
        "scope": "Only the supplied posts directory, not the entire account or other export folders.",
        "inspection": "Metadata and decoding are not visual or full-resolution inspection.",
        "usage_manifest": str(usage_manifest.resolve()),
        "usage_manifest_sha256": sha256(usage_manifest.read_bytes()).hexdigest(),
        "files": records,
    }
    output.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory(prefix="image-review-staging-", dir=output.parent) as temporary:
        staging = Path(temporary) / "complete"
        staging.mkdir()
        sheets = [render_sheet(batch, f"batch-{number:02}", staging)
                  for number, batch in enumerate(groups(pending), 1)]
        for sheet in sheets:
            write_new(staging / "drafts" / f"{sheet['id']}.json", {
                "status": "unreviewed", "summary": "",
                "items": [{"id": image_id, "classification": None, "selection": None,
                           "reason": "", "risks": [], "needs_focus": False}
                          for image_id in sheet["ids"]],
            })
        write_new(staging / "inventory.json", inventory)
        if owner_path:
            write_new(staging / "owner-classifications.json", read_json(owner_path))
        columns = list(records[0])
        text = StringIO(newline="")
        writer = csv.DictWriter(text, fieldnames=columns)
        writer.writeheader()
        for record in records:
            writer.writerow({**record, "existing_website_cake_ids": ";".join(record["existing_website_cake_ids"])})
        save_preserving_existing(staging / "inventory.csv", text.getvalue().encode("utf-8-sig"))
        write_new(staging / "sheets.json", {"sheets": sheets})
        verify_sources(staging)
        staging.rename(output)
    return output


def verify_sources(output):
    inventory = read_json(output / "inventory.json")
    root = Path(inventory["source_root"])
    records = inventory["files"]
    owner_path = output / "owner-classifications.json"
    owner_classifications(owner_path if owner_path.exists() else None, records)
    if {str(path) for path in source_files(root)} != {record["path"] for record in records}:
        raise ValueError("Source directory membership changed.")
    for record in records:
        path = Path(record["path"])
        if sha256(source_data(path)).hexdigest() != record["sha256"]:
            raise ValueError(f"Original hash changed: {path}")
        if path.stat().st_mtime_ns != record["mtime_ns"]:
            raise ValueError(f"Original modification time changed: {path}")
    for sheet in all_sheets(output):
        path = output / sheet["file"]
        if sha256(path.read_bytes()).hexdigest() != sheet["sha256"]:
            raise ValueError(f"Contact sheet changed: {path}")
    return len(records)


def all_sheets(output):
    sheets = read_json(output / "sheets.json")["sheets"]
    for path in sorted((output / "focus").glob("*.json")):
        sheets.append(read_json(path))
    return sheets


def audit_session(events):
    calls, completed, view_ids = [], {}, set()
    # Session logs can contain large image payloads; retain only view accounting.
    with events.open(encoding="utf-8") as stream:
        for line in stream:
            event = json.loads(line)
            data = event.get("data", {})
            if event.get("type") == "tool.execution_start" and data.get("toolName", "").split(".")[-1] == "view":
                path = data.get("arguments", {}).get("path", "")
                if Path(path).suffix.lower() in PHOTO_EXTENSIONS | {".ico"}:
                    view_ids.add(data["toolCallId"])
                    calls.append({"call_id": data["toolCallId"], "path": path, "timestamp": event["timestamp"]})
            elif event.get("type") == "tool.execution_complete" and data.get("toolCallId") in view_ids:
                completed[data["toolCallId"]] = data.get("success")
    for call in calls:
        call["success"] = completed.get(call["call_id"])
    return {
        "session_id": events.parent.name, "events_path": str(events.resolve()),
        "audited_at": datetime.now(timezone.utc).isoformat(),
        "image_view_attempts": len(calls),
        "successful_image_views": sum(completed.get(call["call_id"]) is True for call in calls),
        "stop_at_views": STOP_AT_VIEWS, "hard_limit_exclusive": 20,
        "scope": "Conservative view-tool count including failed attempts; no counter reset on compaction.",
        "calls": calls,
    }


def reserve(output, sheet_id, events):
    sheet = next(sheet for sheet in all_sheets(output) if sheet["id"] == sheet_id)
    audit = audit_session(events)
    path = output / sheet["file"]
    viewed = {os.path.normcase(call["path"]) for call in audit["calls"]}
    reservations = [read_json(p) for p in (output / "views").glob("*.json")]
    unused = sum(r["session_id"] == audit["session_id"] and os.path.normcase(r["path"]) not in viewed
                 for r in reservations)
    if audit["image_view_attempts"] + unused >= STOP_AT_VIEWS:
        raise ValueError("STOP: session image budget exhausted. Persist progress and use a fresh session.")
    if os.path.normcase(str(path)) in viewed or any(r["sheet"] == sheet_id for r in reservations):
        raise ValueError("This sheet was already viewed or reserved; use saved findings, not a repeat view.")
    for reservation in reservations:
        if not (output / "decisions" / f"{reservation['sheet']}.json").exists():
            raise ValueError("Record the preceding batch's decisions or explicit failure before another view.")
    if sha256(path.read_bytes()).hexdigest() != sheet["sha256"]:
        raise ValueError("Sheet hash differs from its manifest.")
    write_new(output / "views" / f"{sheet_id}.json",
              {"sheet": sheet_id, "path": str(path), "session_id": audit["session_id"],
               "reserved_at": audit["audited_at"], "budget_before": audit["image_view_attempts"] + unused})
    return path


def record_batch(output, sheet_id, decision_file, events):
    sheet = next(sheet for sheet in all_sheets(output) if sheet["id"] == sheet_id)
    if sha256((output / sheet["file"]).read_bytes()).hexdigest() != sheet["sha256"]:
        raise ValueError("Sheet hash differs from its manifest.")
    reservation = read_json(output / "views" / f"{sheet_id}.json")
    audit = audit_session(events)
    decision = read_json(decision_file)
    if not str(decision.get("summary", "")).strip():
        raise ValueError("Every batch needs an observation or failure summary.")
    if decision.get("status") in {"view-failed", "interrupted-unclassified"}:
        if decision.get("items"):
            raise ValueError("A failed or interrupted view cannot supply visual classifications.")
    elif decision.get("status") == "reviewed":
        if reservation["session_id"] != audit["session_id"]:
            raise ValueError("An interrupted earlier session cannot be reported as a new-session review.")
        matching = [call for call in audit["calls"]
                    if os.path.normcase(call["path"]) == os.path.normcase(reservation["path"])
                    and call["success"] is True
                    and datetime.fromisoformat(call["timestamp"].replace("Z", "+00:00"))
                    >= datetime.fromisoformat(reservation["reserved_at"])]
        if not matching:
            raise ValueError("No successful matching image-view event after the reservation.")
        items = decision.get("items", [])
        if len(items) != len(sheet["ids"]) or {item["id"] for item in items} != set(sheet["ids"]):
            raise ValueError("Supply exactly one decision for every labelled tile in the sheet.")
        for item in items:
            if (item.get("classification") not in CLASSIFICATIONS or item.get("selection") not in SELECTIONS
                    or not str(item.get("reason", "")).strip() or not isinstance(item.get("risks"), list)
                    or type(item.get("needs_focus")) is not bool):
                raise ValueError(f"Invalid or incomplete classification: {item.get('id')}")
            if item["classification"] == "uncertain" and (item["selection"] != "hold" or not item["needs_focus"]):
                raise ValueError("Uncertain images must stay on hold for focused review.")
    else:
        raise ValueError("Batch status must be reviewed, view-failed or interrupted-unclassified.")
    write_new(output / "decisions" / f"{sheet_id}.json",
              {**decision, "sheet": sheet_id, "session_id": audit["session_id"],
               "reserved_session_id": reservation["session_id"],
               "review_level": "contact-sheet-only", "recorded_at": audit["audited_at"]})


def focus(output, name, ids, reason):
    if not name.startswith("focus-") or not name.replace("-", "").isalnum():
        raise ValueError("Use a simple focus-NN name.")
    if not reason.strip():
        raise ValueError("Record why this focused comparison is necessary.")
    records = {record["id"]: record for record in read_json(output / "inventory.json")["files"]}
    if len(set(ids)) != len(ids):
        raise ValueError("Focus IDs must be unique.")
    selected = [records[image_id] for image_id in ids]
    if any(record["decode_status"] != "ok" for record in selected):
        raise ValueError("Focus sheets require successfully decoded still images.")
    sheet = render_sheet(selected, name, output)
    write_new(output / "focus" / f"{name}.json", {**sheet, "reason": reason})


def report(output, destination, events):
    destination = Path(os.path.abspath(destination))
    check_local_path(destination)
    if not destination.is_relative_to(ROOT / "docs"):
        raise ValueError("The review report must be in this project's docs directory.")
    if destination.exists() and not destination.read_text(encoding="utf-8").startswith(REPORT_MARKER):
        raise ValueError("Refusing to overwrite a manually authored document.")
    inventory = read_json(output / "inventory.json")
    records = inventory["files"]
    owner_path = output / "owner-classifications.json"
    owners = owner_classifications(owner_path if owner_path.exists() else None, records)
    audit = audit_session(events)
    replace_generated(output / "session-budget.json", json_bytes(audit))
    decisions, batch_status = {}, {}
    saved = [read_json(p) for p in (output / "decisions").glob("*.json")]
    for batch in sorted(saved, key=lambda item: item["recorded_at"]):
        batch_status[batch["sheet"]] = batch["status"]
        for item in batch.get("items", []):
            decisions[item["id"]] = {**item, "sheet": batch["sheet"]}
    rows = []
    for record in records:
        classification, selection, reason = "unreviewed", "pending", "No visual classification yet."
        if record["duplicate_of"]:
            classification, selection = "exact-byte-duplicate", "exclude-redundant-review"
            reason = f"Same SHA-256 as {record['duplicate_of']}; preserve both originals."
        elif record["existing_website_cake_ids"]:
            classification, selection = "cake-prior-selection", "already-used-source"
            reason = "Hash matches existing photo provenance: " + ", ".join(record["existing_website_cake_ids"])
        elif record["decode_status"] != "ok":
            classification, selection, reason = record["decode_status"], "hold", record["error"] or record["decode_status"]
        if record["id"] in decisions:
            item = decisions[record["id"]]
            classification, selection, reason = item["classification"], item["selection"], item["reason"]
        if record["id"] in owners:
            item = owners[record["id"]]
            classification, selection = f"owner-confirmed-{item['classification']}", "owner-selected-source"
            reason = f"{item['label']}: {item['reason']}"
        rows.append({**record, "classification": classification, "selection": selection, "reason": reason})
    counts = Counter(row["classification"] for row in rows)
    lines = [
        REPORT_MARKER, "# Bounded posts-image review", "",
        f"Source: `{inventory['source_root']}`.", "",
        f"Inventory: **{len(records)} files / {len({r['sha256'] for r in records})} distinct SHA-256 values**.",
        f"Classifications: `{dict(counts)}`.", "",
        f"Session `{audit['session_id']}`: **{audit['successful_image_views']} successful prior image views; "
        f"{audit['image_view_attempts']} attempts counted**. Stop threshold: {STOP_AT_VIEWS}; hard limit: below 20.",
        "**PAUSED: use a fresh session before viewing any sheet.**" if audit["image_view_attempts"] >= STOP_AT_VIEWS
        else "**Review may proceed one reserved sheet at a time; save each batch before the next view.**",
        "", "No new visual inspection is implied by inventory, decoding or sheet generation.",
        "Contact-sheet inspection is not full-resolution inspection or permission to publish.",
        "Prior selections are inherited only by an exact source-hash match, not re-inspected here.",
        "Owner-confirmed rows come from explicit supplied-source classifications, not new contact-sheet or cutout review.",
        "Duplicate exclusion means no redundant review, not deletion or rejection of the cake.",
        "", "## Private artifacts", "",
        f"- Inventory JSON: `{output / 'inventory.json'}`.",
        f"- Inventory CSV: `{output / 'inventory.csv'}`.",
        f"- Sheet manifest: `{output / 'sheets.json'}`.",
        f"- Budget audit: `{output / 'session-budget.json'}`.",
        f"- Batch decisions: `{output / 'decisions'}`.",
        "", "## Sequential batches", "",
        "| Sheet | Images | Status | Saved path (do not auto-open) |",
        "| --- | ---: | --- | --- |",
    ]
    for sheet in all_sheets(output):
        status = batch_status.get(sheet["id"], "reserved-unrecorded" if (output / "views" / f"{sheet['id']}.json").exists() else "not-viewed")
        lines.append(f"| {sheet['id']} | {len(sheet['ids'])} | {status} | `{output / sheet['file']}` |")
    lines += ["", "## Per-file classification ledger", "",
              "Full absolute paths, dimensions, hashes and duplicate associations are in the inventory.",
              "Descriptions are visual design labels only; do not infer flavour, ingredients or customer identity.", "",
              "| ID | Original filename | Classification | Selection | Reason |",
              "| --- | --- | --- | --- | --- |"]
    for row in rows:
        cells = [row["id"], row["filename"], row["classification"], row["selection"], row["reason"]]
        lines.append("| " + " | ".join(str(cell).replace("|", "\\|").replace("\n", " ") for cell in cells) + " |")
    for batch in saved:
        lines += ["", f"## {batch['sheet']} - {batch['status']}", "", batch["summary"],
                  "", "Evidence level: contact sheet only. No full-resolution or publication approval."]
    replace_generated(destination, ("\n".join(lines) + "\n").encode("utf-8"))
    return {"files": len(records), "classifications": dict(counts), "sheets": len(all_sheets(output)),
            "successful_image_views": audit["successful_image_views"], "report": str(destination)}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, required=True)
    commands = parser.add_subparsers(dest="command", required=True)
    preparation = commands.add_parser("prepare")
    preparation.add_argument("source", type=Path)
    preparation.add_argument("--usage-manifest", type=Path, default=ROOT / "assets" / "images" / "cakes" / "manifest.json")
    preparation.add_argument("--owner-classifications", type=Path, help="Hash-bound owner source decisions; excluded from repeat viewing.")
    commands.add_parser("verify")
    focused = commands.add_parser("focus")
    focused.add_argument("name")
    focused.add_argument("--ids", nargs="+", required=True)
    focused.add_argument("--reason", required=True)
    for command in ("report", "reserve", "record"):
        subparser = commands.add_parser(command)
        subparser.add_argument("--events", type=Path, required=True)
        if command != "report":
            subparser.add_argument("sheet")
        if command == "record":
            subparser.add_argument("--decisions", type=Path, required=True)
        if command in ("record", "report"):
            subparser.add_argument("--report", type=Path, required=True)
    args = parser.parse_args()
    output = private_output(args.output)
    if args.command == "prepare":
        prepare(args.source, output, args.usage_manifest, args.owner_classifications)
        print(f"Prepared inventory and unopened contact sheets: {output}")
    elif args.command == "verify":
        print(f"Verified unchanged bytes/mtimes for {verify_sources(output)} originals and all sheet hashes.")
    elif args.command == "focus":
        focus(output, args.name, args.ids, args.reason)
        print(f"Prepared unopened focused sheet: {output / 'sheets' / (args.name + '.jpg')}")
    elif args.command == "reserve":
        print(reserve(output, args.sheet, args.events))
    else:
        if args.command == "record":
            record_batch(output, args.sheet, args.decisions, args.events)
        print(json.dumps(report(output, args.report, args.events), indent=2))


